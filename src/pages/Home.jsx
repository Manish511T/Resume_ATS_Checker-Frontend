import { useCallback, useEffect, useState } from "react";
import { Loader2 } from "lucide-react";
import Hero from "../components/Hero.jsx";
import JobDescriptionSelect from "../components/JobDescriptionSelect.jsx";
import ResumeUpload, { validatePdf } from "../components/ResumeUpload.jsx";
import AnalysisResults from "../components/AnalysisResults.jsx";
import LoadingState from "../components/LoadingState.jsx";
import ErrorMessage from "../components/ErrorMessage.jsx";
import { fetchJobs, analyzeResume } from "../services/api.js";

export default function Home() {
  const [jobs, setJobs] = useState([]);
  const [jobsLoading, setJobsLoading] = useState(true);
  const [jobsError, setJobsError] = useState("");
  const [jobId, setJobId] = useState("");
  const [file, setFile] = useState(null);
  const [fileError, setFileError] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [submitError, setSubmitError] = useState("");
  const [result, setResult] = useState(null);

  const loadJobs = useCallback(async () => {
    setJobsLoading(true);
    setJobsError("");
    try {
      setJobs(await fetchJobs());
    } catch (e) {
      setJobsError(e.message);
    } finally {
      setJobsLoading(false);
    }
  }, []);

  useEffect(() => { loadJobs(); }, [loadJobs]);

  const handleSelect = (f) => {
    const problem = validatePdf(f);
    setFileError(problem);
    setFile(problem ? null : f);
    setResult(null);
  };

  const canSubmit = Boolean(jobId && file) && !submitting;

  const handleSubmit = async (e) => {
    e.preventDefault();
    if (submitting) return;
    if (!jobId) return setSubmitError("Select a job role first.");
    if (!file) return setFileError("Select a PDF resume first.");
    setSubmitting(true);
    setSubmitError("");
    setResult(null);
    try {
      setResult(await analyzeResume(file, jobId));
    } catch (err) {
      setSubmitError(err.message);
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <main>
      <Hero />

      <section id="analyze" className="mx-auto max-w-3xl scroll-mt-16 px-5 py-16">
        <form onSubmit={handleSubmit} className="space-y-6 rounded-2xl border border-pine-100 bg-white/60 p-6 shadow-sm sm:p-8">
          <h2 className="font-display text-2xl font-bold text-pine-900">Analyze your resume</h2>
          <JobDescriptionSelect jobs={jobs} loading={jobsLoading} error={jobsError} selectedId={jobId}
            onChange={(v) => { setJobId(v); setSubmitError(""); }} onRetry={loadJobs} disabled={submitting} />
          <ResumeUpload file={file} error={fileError} onSelect={handleSelect}
            onRemove={() => { setFile(null); setFileError(""); setResult(null); }} disabled={submitting} />
          <ErrorMessage message={submitError} />
          <button type="submit" disabled={!canSubmit}
            className="flex w-full items-center justify-center gap-2 rounded-xl bg-pine-700 px-6 py-3 font-semibold text-white hover:bg-pine-900 focus:outline-none focus-visible:ring-4 focus-visible:ring-pine-600/30 disabled:cursor-not-allowed disabled:opacity-50">
            {submitting && <Loader2 className="h-5 w-5 animate-spin" />}
            Analyze Resume
          </button>
          {submitting && <LoadingState message="Analyzing your resume..." />}
        </form>

        {result && <AnalysisResults result={result} />}
      </section>

      <section id="about" className="scroll-mt-16 border-t border-pine-100 bg-pine-50/60">
        <div className="mx-auto max-w-3xl px-5 py-16">
          <h2 className="font-display text-2xl font-bold text-pine-900">About</h2>
          <p className="mt-4 leading-relaxed text-ink/80">
            ATS Resume Checker compares your resume with a job description you choose. The backend APIs are built with
            Django REST Framework. Text is extracted from your PDF with pdfplumber, and the analysis is generated by a
            large language model hosted on Groq. This interface is built with React.
          </p>
          <p className="mt-3 text-sm text-ink/60">
            Results are AI-generated estimates from the text of your PDF. They are meant as guidance, not as an official ATS verdict.
          </p>
        </div>
      </section>
    </main>
  );
}
